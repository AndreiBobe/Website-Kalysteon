let _lang = "en";

function setLang(l) {
  _lang = I18N_DICT[l] ? l : "en";
}

function t(key, vars) {
  let s = (I18N_DICT[_lang] && I18N_DICT[_lang][key]) ||
          (I18N_DICT.en[key]) ||
          key;
  if (vars && typeof vars === "object") {
    for (const k of Object.keys(vars)) {
      s = s.split("{" + k + "}").join(vars[k]);
    }
  }
  return s;
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach(el => {
    // <optgroup> a un .label attribute, pas un textContent visible.
    if (el.tagName === "OPTGROUP") {
      el.label = t(el.dataset.i18n);
    } else {
      el.textContent = t(el.dataset.i18n);
    }
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  // Met à jour <html lang="">
  document.documentElement.lang = _lang;
}

window.I18N = { setLang, t, applyI18n, getLang: () => _lang };
